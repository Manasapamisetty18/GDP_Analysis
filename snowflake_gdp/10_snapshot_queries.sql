

USE DATABASE GDP_ANALYTICS;


-- Create Snapshot Schema (if not exists)


CREATE SCHEMA IF NOT EXISTS SNAPSHOTS;


-- View Snapshot Data


SELECT *
FROM SNAPSHOTS.COUNTRY_SNAPSHOT;


-- Verify Country Data Before Snapshot


SELECT
    COUNTRY_ID,
    COUNTRY_NAME,
    INCOME_GROUP
FROM RAW.RAW_COUNTRIES;


-- Check Specific Country


SELECT
    COUNTRY_ID,
    COUNTRY_NAME,
    INCOME_GROUP
FROM RAW.RAW_COUNTRIES
WHERE COUNTRY_NAME = 'India';


-- Test Data Change


UPDATE RAW.RAW_COUNTRIES
SET INCOME_GROUP = 'High'
WHERE COUNTRY_NAME = 'India';


-- Validate Changes


SELECT
    COUNTRY_ID,
    COUNTRY_NAME,
    INCOME_GROUP
FROM RAW.RAW_COUNTRIES
WHERE COUNTRY_NAME = 'India';


-- Check Duplicate Country IDs


SELECT COUNT(*) AS TOTAL_RECORDS
FROM RAW.RAW_COUNTRIES;

SELECT COUNT(DISTINCT COUNTRY_ID) AS DISTINCT_COUNTRY_IDS
FROM RAW.RAW_COUNTRIES;




-- Drop Snapshot Table (Cleanup)


DROP TABLE IF EXISTS SNAPSHOTS.COUNTRY_SNAPSHOT;